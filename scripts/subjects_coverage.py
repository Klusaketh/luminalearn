"""
LuminaLearn AI — Subjects syllabus coverage report.

Audits every topic's lesson file against the completeness rules in subject_content.py and writes
docs/SUBJECTS_COVERAGE.md: one row per topic with what is present and whether it counts as complete.

Run: python scripts/subjects_coverage.py          (add --check to exit 1 while anything is incomplete)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from scripts.subject_content import (  # noqa: E402
    MIN_PRACTICE_QUESTIONS,
    OVERVIEW_SECTIONS,
    audit_lesson,
    h2_sections,
    iter_topics,
    load_lessons,
    load_overview,
    load_subject_catalog,
    section_text,
)

REPORT = Path(__file__).resolve().parent.parent / "docs" / "SUBJECTS_COVERAGE.md"


def _mark(ok: bool) -> str:
    return "yes" if ok else "**no**"


def build_report() -> tuple[str, int, int]:
    catalog = load_subject_catalog()
    summary_rows: list[str] = []
    detail: list[str] = []
    complete_total = topic_total = 0

    for subject in catalog:
        lessons = load_lessons(subject["slug"])
        overview = load_overview(subject["slug"])
        overview_ok = bool(overview) and all(s in h2_sections(overview or "") for s in OVERVIEW_SECTIONS)
        topics = iter_topics(subject)
        modules = {m["slug"] for (_, m, _) in topics}
        complete = 0
        words = 0
        rows: list[str] = []
        for _, module, topic in topics:
            lesson = lessons.get(topic["slug"])
            if lesson is None:
                rows.append(f"| {module['title']} | {topic['title']} | **no** | **no** | **no** | **no** | 0 | **no** | missing |")
                continue
            audit = audit_lesson(lesson)
            words += audit.words
            complete += audit.complete
            levels = ", ".join(f"{n} {lvl}" for lvl, n in sorted(audit.levels.items()))
            rows.append(
                "| {module} | {topic} | {theory} | {examples} | {apps} | {revision} | {q} ({levels}) | {answers} | {status} |".format(
                    module=module["title"],
                    topic=topic["title"],
                    theory=_mark(bool(section_text(lesson.content, "Core theory"))),
                    examples=f"{audit.worked_examples}" if audit.worked_examples else "**0**",
                    apps=_mark(bool(section_text(lesson.content, "Applications"))),
                    revision=_mark(bool(section_text(lesson.content, "Revision notes"))),
                    q=audit.questions,
                    levels=levels or "none",
                    answers=_mark(audit.questions >= MIN_PRACTICE_QUESTIONS and audit.unanswered == 0),
                    status="complete" if audit.complete else "incomplete: " + "; ".join(
                        audit.issues
                        + [f"missing {', '.join(audit.missing_sections)}"] * bool(audit.missing_sections)
                        + [f"{audit.words} words"] * (audit.words < 900)
                    ),
                )
            )
        complete_total += complete
        topic_total += len(topics)
        summary_rows.append(
            f"| {subject['name']} | {len(modules)} | {len(topics)} | {len(lessons)} | {complete} | {words:,} | {_mark(overview_ok)} |"
        )
        detail.append(f"\n### {subject['name']}\n")
        detail.append("| Module | Topic | Theory | Worked examples | Applications | Revision notes | Practice questions | Answers | Status |")
        detail.append("| :--- | :--- | :---: | :---: | :---: | :---: | :--- | :---: | :--- |")
        detail.extend(rows)

    header = [
        "# Subjects Syllabus Coverage",
        "",
        "Generated by `python scripts/subjects_coverage.py` from the files in `content/subjects/`. "
        "A topic counts as complete only when its lesson has every required section (introduction, core theory, "
        f"worked examples, applications, common mistakes, revision notes, practice questions, further learning), at least one worked example, "
        f"at least {MIN_PRACTICE_QUESTIONS} practice questions each with an answer and explanation, and enough depth (900+ words).",
        "",
        "The curriculum is a foundational syllabus written for LuminaLearn. It is not an official syllabus of any institution, "
        "and it carries no course codes or examination mappings.",
        "",
        f"**Complete topics: {complete_total} / {topic_total}**",
        "",
        "| Subject | Modules | Topics | Lessons | Complete | Words | Overview |",
        "| :--- | ---: | ---: | ---: | ---: | ---: | :---: |",
        *summary_rows,
        "",
        "## Topic detail",
    ]
    return "\n".join(header + detail) + "\n", complete_total, topic_total


def main() -> int:
    report, complete, total = build_report()
    REPORT.write_text(report, encoding="utf-8")
    print(f"Complete topics: {complete} / {total}  ->  {REPORT}")
    return 1 if "--check" in sys.argv and complete < total else 0


if __name__ == "__main__":
    sys.exit(main())
